test('older analysis is refreshed before making correction or exclusion decisions',async({page})=>{
  await page.goto('/')
  await page.getByLabel('이메일').fill('admin@example.invalid')
  await page.getByLabel('비밀번호',{exact:true}).fill('synthetic test password')
  await page.getByRole('button',{name:'로그인',exact:true}).click()
  await page.getByRole('button',{name:'상품 조회 화면 열기'}).click()
  await page.getByRole('link',{name:'데이터 가져오기'}).click()
  await page.getByLabel('Master Excel 파일').setInputFiles({name:'old-policy.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:workbook(true)})
  await page.getByRole('button',{name:'분석 시작'}).click()
  await page.getByRole('button',{name:'검증 결과 저장'}).click()
  await expect(page.getByText('검증 결과가 중앙 저장소에 저장되었습니다.')).toBeVisible()
  let showOldPolicy=true
  await page.route('**/api/import/batches',async route=>{
    if(route.request().method()!=='GET' || !showOldPolicy){await route.continue();return}
    const response=await route.fetch();const rows=await response.json() as Record<string,unknown>[]
    await route.fulfill({response,json:rows.map(row=>row.source_filename==='old-policy.xlsx'?{...row,parser_version:'master-v1.0.0'}:row)})
  })
  await page.reload()
  await page.getByRole('button',{name:'상품 조회 화면 열기'}).click()
  await page.getByRole('button',{name:'old-policy.xlsx 배치 상세 보기'}).click()
  const correction=page.getByRole('region',{name:'직접 수정 및 재검증'})
  await expect(correction).toContainText('이전 검증 기준')
  await expect(correction.getByRole('button',{name:'이번 적용에서 제외'})).toHaveCount(0)
  showOldPolicy=false
  await correction.getByRole('button',{name:'현재 기준으로 다시 검증'}).click()
  await expect(page.getByRole('region',{name:'직접 수정 및 재검증'}).getByText('오류 사유와 처리')).toBeVisible()
})
