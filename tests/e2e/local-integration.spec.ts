import { expect,test } from '@playwright/test'
import * as XLSX from 'xlsx'

function workbook(includeValid=false):Buffer {
  const price:unknown[][]=Array.from({length:6},()=>[])
  price[4][1]='사방넷품번';price[4][2]='구분';price[4][3]='카테고리';price[4][4]='모델명';price[4][5]='구성 상세';price[4][7]='구성수'
  price[5][1]='';price[5][2]='단품';price[5][3]='냉동용기';price[5][4]='점보';price[5][5]='AL99 1개';price[5][7]=1
  if(includeValid){price[6]=[];price[6][1]='100052';price[6][2]='단품';price[6][3]='냉동용기';price[6][4]='정상';price[6][5]='AL00 1개';price[6][7]=1}
  const codes:unknown[][]=Array.from({length:5},()=>[]);codes[2][2]='상품명';codes[2][3]='옵션명';codes[2][4]='상품코드';codes[3][1]='냉동용기';codes[4][2]='점보';codes[4][3]='라벤더';codes[4][4]='AL00'
  const products:unknown[][]=Array.from({length:4},()=>[]);products[2][0]='마스터 상품명';products[2][2]='사방넷 품번코드'
  const book=XLSX.utils.book_new();XLSX.utils.book_append_sheet(book,XLSX.utils.aoa_to_sheet(price),'단가표');XLSX.utils.book_append_sheet(book,XLSX.utils.aoa_to_sheet(codes),'코드DB');XLSX.utils.book_append_sheet(book,XLSX.utils.aoa_to_sheet(products),'상품DB')
  return XLSX.write(book,{bookType:'xlsx',type:'buffer'}) as Buffer
}

