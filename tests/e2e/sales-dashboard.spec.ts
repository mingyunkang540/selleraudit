import {expect,test} from '@playwright/test'
import {createSeedData} from '../../src/mock'
import * as XLSX from 'xlsx'
import {readFile} from 'node:fs/promises'

test('매출 대시보드에서 기간과 채널을 선택하고 원본 차이를 확인한다',async({page})=>{
 const data=createSeedData()
 const snapshot={schemaVersion:1,sourceName:'매출.xlsx',sourcePath:'C:/example/매출.xlsx',sourceSha256:'hash',asOf:'2026-11-02',days:[{date:'2024-01-01',total:77,groupBuy:null,channels:{A:30,B:47},sourceRow:0},{date:'2026-10-31',total:100,groupBuy:20,groupBuyChannels:{A:20},channels:{A:60,B:40},sourceRow:46},{date:'2026-11-01',total:200,groupBuy:50,groupBuyChannels:{A:50},channels:{A:80,B:120},sourceRow:16},{date:'2026-11-02',total:300,groupBuy:100,groupBuyChannels:{B:100},channels:{A:100,B:200},sourceRow:17}],months:[{month:'2024-01'},{month:'2026-10'},{month:'2026-11'}],warnings:[{type:'MONTH_SUMMARY_MISMATCH',sheet:'26년10월 매출',cached:0,calculated:100}]}
 await page.route('**/api/**',async route=>{const path=new URL(route.request().url()).pathname
  if(path==='/api/auth/session')return route.fulfill({json:{openMode:true,user:{userId:'u',workspaceId:data.workspace.id,role:'ADMIN',email:'admin@example.com',displayName:'Admin'},csrf:'fake',importEnabled:true}})
  if(path==='/api/data')return route.fulfill({json:data})
  if(path==='/api/sales-dashboard')return route.fulfill({json:snapshot})
  if(path==='/api/product-configurations')return route.fulfill({json:{configurations:[],bindings:[]}})
  return route.fulfill({json:{employees:[]}})
 })
 await page.goto('/#/sales')
 await expect(page.getByRole('heading',{name:'매출 대시보드'})).toBeVisible()
 await expect(page.getByText('매출 기록 기준 2026-11-02까지')).toBeVisible()
 await expect(page.getByText('원본: 매출.xlsx')).toBeVisible()
 await page.getByLabel('월별 조회').selectOption('m:2024-01')
 await expect(page.locator('.sales-kpi').first()).toContainText('77원')
 await page.getByLabel('월별 조회').selectOption('m:2026-11')
 await page.getByText('매출 집계 기준').click()
 await expect(page.getByText(/엑셀을 저장하면 약 15초마다/)).toBeVisible()
 await expect(page.locator('.sales-kpi').first()).toContainText('500원')
 await expect(page.getByText('원본 집계 확인 사항')).toHaveCount(0)
 await page.getByRole('button',{name:'일별',exact:true}).click()
 await expect(page.locator('.sales-bar-group')).toHaveCount(2)
 const firstBar=page.locator('.sales-bar-track').first()
 await expect(firstBar).toHaveAttribute('aria-label',/2026-11-01 전체 200원.*공동구매 50원/)
 await firstBar.focus()
 await expect(firstBar.locator('.sales-bar-tooltip')).toBeVisible()
 await expect(page.getByRole('img',{name:/전체 채널 매출 500원/})).toBeVisible()
 await firstBar.click()
 await expect(firstBar).toHaveAttribute('aria-pressed','true')
 await expect(page.locator('.sales-share')).toContainText('2026-11-01')
 await expect(page.locator('.sales-share .sales-donut')).toHaveAttribute('aria-label',/200원/)
 await expect(page.locator('.sales-kpi').first()).toContainText('500원')
 await page.getByRole('button',{name:'날짜 선택 해제'}).click()
 await expect(page.locator('.sales-share .sales-donut')).toHaveAttribute('aria-label',/500원/)
 await firstBar.focus()
 await page.keyboard.press('Enter')
 await expect(page.locator('.sales-share')).toContainText('2026-11-01')
 await firstBar.click()
 await expect(page.locator('.sales-share .sales-donut')).toHaveAttribute('aria-label',/500원/)
 await expect(page.locator('.sales-monthly').getByRole('heading',{name:'일별 매출'})).toBeVisible()
 await expect(page.locator('.sales-monthly-row')).toHaveCount(2)
 await expect(page.locator('.sales-monthly-row').first()).toContainText('2026-11-02')
 await expect(page.locator('.sales-monthly-row').first()).toContainText('300원')
 await expect(page.locator('.sales-monthly-row').first()).toContainText('공구 제외 200원')
 await expect(page.locator('.sales-bar-column').filter({hasText:'11/1'})).toHaveAttribute('title',/공동구매 50원.*공구 제외 150원/)
 await page.getByRole('button',{name:'공동구매 제외',exact:true}).click()
 await expect(page.locator('.sales-export').getByRole('button',{name:'공동구매 제외'})).toBeVisible()
 await expect(page.locator('.sales-share .sales-donut')).toHaveAttribute('aria-label',/350원/)
 await firstBar.click()
 await expect(page.locator('.sales-share .sales-donut')).toHaveAttribute('aria-label',/150원/)
 await expect(page.locator('.sales-share')).toContainText('2026-11-01')
 await page.getByRole('button',{name:'날짜 선택 해제'}).click()
 await expect(page.locator('.sales-share')).toContainText('기록된 공동구매 제외')
 await expect(page.locator('.sales-monthly-row').first()).toContainText('200원')
 await expect(page.locator('.sales-bar-track').first()).toHaveAttribute('aria-label',/매출 150원/)
 await expect(page.locator('.sales-bar-group')).toHaveCount(0)
 await expect(page.locator('.sales-kpi').first()).toContainText('500원')
 await page.getByLabel('매출 채널').selectOption('A')
 await expect(page.getByRole('button',{name:'공동구매 제외'})).toBeDisabled()
 await page.getByLabel('매출 채널').selectOption('ALL')
 await expect(page.getByRole('button',{name:'공동구매 제외'})).toHaveAttribute('aria-pressed','true')
 await page.getByRole('button',{name:'공동구매 포함',exact:true}).click()
 await expect(page.locator('.sales-bar-group')).toHaveCount(2)
 await expect(page.locator('.sales-share .sales-donut')).toHaveCount(1)
 await page.getByLabel('매출 채널').selectOption('A')
 await expect(page.locator('.sales-bar-group')).toHaveCount(0)
 await expect(page.locator('.sales-kpi').first()).toContainText('180원')
 await page.getByRole('button',{name:'1개월'}).click()
 await expect(page.locator('.sales-kpi').first()).toContainText('240원')
 await expect(page.getByLabel('시작일')).toHaveValue('2026-10-03')
 await page.getByRole('button',{name:'월별',exact:true}).click()
 await expect(page.locator('.sales-chart').getByRole('heading',{name:'월별 매출'})).toBeVisible()
 await expect(page.locator('.sales-monthly').getByRole('heading',{name:'월별 매출'})).toBeVisible()
 await expect(page.locator('.sales-monthly-row').filter({hasText:'2026-10'})).toBeVisible()
 await page.getByLabel('시작일').fill('2026-11-01')
 await page.getByLabel('종료일').fill('2026-11-01')
 await expect(page.locator('.sales-kpi').first()).toContainText('80원')
 await page.getByLabel('월별 조회').selectOption('m:2026-10')
 await expect(page.locator('.sales-kpi').first()).toContainText('60원')
 await page.getByRole('button',{name:'1년'}).click()
 await expect(page.getByLabel('시작일')).toHaveValue('2025-11-03')
 const pending=page.waitForEvent('download')
 await page.getByRole('button',{name:'엑셀 다운로드'}).click()
 const download=await pending
 const path=await download.path()
 const book=XLSX.read(await readFile(path),{type:'buffer'})
 const sheet=book.Sheets['매출 내역']
 expect(sheet.A8.v).toBe('2026-10-31')
 expect(sheet.B8.v).toBe(60)
 expect(sheet.A11.v).toBe('합계')
 expect(sheet.B11.v).toBe(240)
 await page.getByLabel('매출 채널').selectOption('ALL')
 await page.getByLabel('엑셀 집계 단위').selectOption('month')
 const pendingMonthly=page.waitForEvent('download')
 await page.getByRole('button',{name:'엑셀 다운로드'}).click()
 const monthly=XLSX.read(await readFile(await (await pendingMonthly).path()),{type:'buffer'}).Sheets['매출 내역']
 expect(monthly.A8.v).toBe('2026-10')
 expect(monthly.B8.v).toBe(100)
 expect(monthly.B9.v).toBe(500)
 expect(monthly.B10.v).toBe(600)
})
